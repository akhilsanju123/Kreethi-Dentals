/*
# Create clinic public forms

1. New Tables
- `appointments` stores patient appointment requests with contact details, requested treatment, date/time, and an internal workflow status.
- `contact_messages` stores contact form enquiries for clinic follow-up.

2. Security
- Both tables have Row Level Security enabled.
- Anonymous visitors may submit new requests but cannot read, edit, or delete patient-submitted records.
- Authenticated staff can read and update submitted records for administration.
- Grants are limited to the operations used by the public forms and staff dashboard.

3. Important Notes
- Appointment requests are not confirmations; clinic staff must confirm them.
- Booking references are generated by the database for support follow-up.
*/

CREATE TABLE IF NOT EXISTS public.appointments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  booking_reference text NOT NULL UNIQUE DEFAULT ('KCD-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8))),
  full_name text NOT NULL CHECK (char_length(full_name) BETWEEN 2 AND 120),
  phone text NOT NULL CHECK (char_length(phone) BETWEEN 7 AND 30),
  email text CHECK (email IS NULL OR char_length(email) <= 254),
  treatment_interest text NOT NULL CHECK (char_length(treatment_interest) BETWEEN 2 AND 120),
  preferred_doctor text,
  preferred_date date NOT NULL,
  preferred_time text NOT NULL,
  message text CHECK (message IS NULL OR char_length(message) <= 2000),
  privacy_consent boolean NOT NULL DEFAULT false CHECK (privacy_consent = true),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'rescheduled', 'completed', 'cancelled')),
  internal_notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.contact_messages (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  full_name text NOT NULL CHECK (char_length(full_name) BETWEEN 2 AND 120),
  phone text NOT NULL CHECK (char_length(phone) BETWEEN 7 AND 30),
  email text CHECK (email IS NULL OR char_length(email) <= 254),
  subject text NOT NULL CHECK (char_length(subject) BETWEEN 2 AND 160),
  message text NOT NULL CHECK (char_length(message) BETWEEN 2 AND 3000),
  privacy_consent boolean NOT NULL DEFAULT false CHECK (privacy_consent = true),
  status text NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'in_progress', 'resolved')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS appointments_status_created_idx ON public.appointments (status, created_at DESC);
CREATE INDEX IF NOT EXISTS contact_messages_status_created_idx ON public.contact_messages (status, created_at DESC);

ALTER TABLE public.appointments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contact_messages ENABLE ROW LEVEL SECURITY;

GRANT INSERT ON public.appointments TO anon, authenticated;
GRANT INSERT ON public.contact_messages TO anon, authenticated;
GRANT SELECT, UPDATE ON public.appointments TO authenticated;
GRANT SELECT, UPDATE ON public.contact_messages TO authenticated;

DROP POLICY IF EXISTS "Public can submit appointments" ON public.appointments;
CREATE POLICY "Public can submit appointments" ON public.appointments FOR INSERT TO anon, authenticated WITH CHECK (privacy_consent = true);
DROP POLICY IF EXISTS "Staff can view appointments" ON public.appointments;
CREATE POLICY "Staff can view appointments" ON public.appointments FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "Staff can update appointments" ON public.appointments;
CREATE POLICY "Staff can update appointments" ON public.appointments FOR UPDATE TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public can submit contact messages" ON public.contact_messages;
CREATE POLICY "Public can submit contact messages" ON public.contact_messages FOR INSERT TO anon, authenticated WITH CHECK (privacy_consent = true);
DROP POLICY IF EXISTS "Staff can view contact messages" ON public.contact_messages;
CREATE POLICY "Staff can view contact messages" ON public.contact_messages FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "Staff can update contact messages" ON public.contact_messages;
CREATE POLICY "Staff can update contact messages" ON public.contact_messages FOR UPDATE TO authenticated USING (true) WITH CHECK (true);
